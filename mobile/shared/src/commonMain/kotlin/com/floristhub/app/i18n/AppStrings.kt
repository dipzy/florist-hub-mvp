val LocalAppLocale = staticCompositionLocalOf { AppLocale.Pt }

data class L10n(
    val pt: StringResource,
    val en: StringResource,
)

@Composable
fun l10nString(pair: L10n, locale: AppLocale = LocalAppLocale.current): String =
    stringResource(if (locale == AppLocale.En) pair.en else pair.pt)

@Composable
fun l10nString(pair: L10n, vararg formatArgs: Any, locale: AppLocale = LocalAppLocale.current): String =
    stringResource(if (locale == AppLocale.En) pair.en else pair.pt, *formatArgs)

